export type MessageKey = keyof typeof pt;
const catalogs: Record<Locale, Record<MessageKey, string>> = { 'pt-BR': pt, en };

export function message(locale: Locale, key: MessageKey, values: Record<string, string | number> = {}): string {
  const template = catalogs[locale]?.[key] ?? pt[key];
  return template.replace(/\{([a-zA-Z]+)\}/g, (_, name: string) => {
    if (!(name in values)) throw new Error(`Missing message value: ${name}`);
    return String(values[name]);
  });
}
